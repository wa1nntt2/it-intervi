try:
    updated = 0
    for q_id, explanation in explanations.items():
        exists = db.execute(
            text("SELECT 1 FROM questions WHERE id = :qid"),
            {"qid": q_id}
        ).first()
        
        if not exists:
            print(f"⚠️  Вопрос ID={q_id} не найден")
            continue
        
        db.execute(
            text("UPDATE questions SET explanation = :expl WHERE id = :qid"),
            {"expl": explanation, "qid": q_id}
        )
        updated += 1
    
    db.commit()
    print(f"✅ Обновлено {updated} описаний.")
    
except Exception as e:
    db.rollback()
    print(f"❌ Ошибка: {e}")
    sys.exit(1)

finally:
    db.close()
